// Función para obtener categorías únicas
export const obtenerCategorias = () => {
  const cats = [...new Set(estilosIniciales.map(e => e.categoria))];
  return cats;
};

// Función para obtener estilos por categoría
export const obtenerEstilosPorCategoria = (categoria) => {
  return estilosIniciales.filter(e => e.categoria === categoria);
};

// Función para buscar estilos
export const buscarEstilos = (query) => {
  const q = query.toLowerCase();
  return estilosIniciales.filter(e => 
    e.nombre.toLowerCase().includes(q) ||
    e.descripcion.toLowerCase().includes(q) ||
    e.tags.some(t => t.includes(q)) ||
    e.categoria.toLowerCase().includes(q)
  );
};
